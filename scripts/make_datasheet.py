"""Render docs/DATASHEET.md — a dataset card for the generated ground truth.

Summarizes provenance, composition, collection method, validation, and limitations from the
produced artifacts (standards.yaml, ground_truth.csv, dataset_quality.csv, judge files), so
the dataset can be released and reviewed responsibly.

Usage:  python scripts/make_datasheet.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.config import Config       # noqa: E402
from src.standards import load_areas  # noqa: E402


def render(cfg: Config) -> str:
    areas = load_areas(cfg)
    gt_path = cfg.path("ground_truth")
    n_q = len(pd.read_csv(gt_path)) if gt_path.exists() else 0
    gen_model = cfg.get("generator_model")
    gt_judges = cfg.get("gt_judges")

    lines = [
        "# Datasheet — NGSS MS-Science Q&A Benchmark Dataset",
        "",
        "_Auto-generated by `scripts/make_datasheet.py`. Edit the generator, not this file._",
        "",
        "## Motivation",
        "Created to benchmark how well LLMs answer middle-school science questions aligned to "
        "the Next Generation Science Standards (NGSS), to guide educators on model choice per "
        "science domain.",
        "",
        "## Composition",
        f"- **{n_q}** question/answer pairs across **{len(areas)}** NGSS disciplinary-core-idea "
        f"areas (target {cfg.get('questions_per_area')} per area).",
        f"- Question types: {', '.join(cfg.get('question_type_split', default={}).keys())} "
        "(labeled per item).",
        "- Each item: area (DCI code), standard (performance expectation), question_type, "
        "question, reference_answer, generator_model, question readability (Flesch-Kincaid).",
        "",
        "## Collection / generation process",
        f"- Questions and reference answers were **LLM-generated** by `{gen_model}`, grounded in "
        "the verbatim NGSS performance-expectation text in `data/standards.yaml`.",
        "- Each candidate question passed a level-appropriateness filter (Flesch-Kincaid band "
        f"{cfg.get('appropriateness', 'fk_grade_range')} + an LLM grade-appropriateness gate) and "
        "an embedding-free near-duplicate check before acceptance. Rejected candidates are logged "
        "in `results/reports/generation_rejects.csv`.",
        "",
        "## Validation",
        f"- A 3-judge LLM panel ({', '.join(gt_judges)}) independently scored each pair; "
        "non-unanimous items are flagged for human review in "
        "`results/human_review/flags_groundtruth.csv`.",
        "- Judge reliability (Fleiss' kappa) and a human-labeled calibration subset "
        "(`results/calibration/`) quantify how trustworthy the automated labels are.",
        "",
        "## Areas covered",
    ]
    for a in areas:
        lines.append(f"- **{a.code}** {a.title} ({len(a.standards)} standards)")
    lines += [
        "",
        "## Limitations",
        "- Questions are LLM-generated and may favor LLMs; consider augmenting with "
        "human/textbook-sourced items.",
        "- The benchmark measures **answer correctness only** — not pedagogical quality, "
        "age-appropriate explanation, hallucination rate, or safety.",
        "- Binary correctness is coarse for open-ended items; a 3-level rubric supplements "
        "conceptual/applied items.",
        "",
        "## Licensing / attribution",
        "- Source standards: NGSS MS topic arrangement, © 2013 Achieve, Inc. (\"all rights "
        "reserved\"); the *Framework for K-12 Science Education* excerpts are reproduced with "
        "permission. NGSS text is confined to `data/standards.yaml` with attribution.",
        "- Generated Q&A are derivative works of the standards text. **Perform a rights/licensing "
        "review before any public release.**",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    cfg = Config.load(require_keys=False)
    out = ROOT / "docs" / "DATASHEET.md"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(cfg))
    print(f"Wrote {out.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
